const at = (time: string, day = '17') => `2026-11-${day}T${time}:00+07:00`
const message = (
  id: string,
  type: Message['type'],
  text: string,
  time: string,
  day = '17',
): Message => ({
  id,
  type,
  text,
  sentAt: at(time, day),
  delivery: type === 'incoming' ? 'delivered' : 'read',
  ...(type !== 'incoming' ? { authorName: 'Linh Nguyen' } : {}),
})

